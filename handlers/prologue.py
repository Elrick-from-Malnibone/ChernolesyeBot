async def send_prologue(update: Update, context: ContextTypes.DEFAULT_TYPE):
    chat_id = update.effective_chat.id

    next_keyboard = InlineKeyboardMarkup([
        [InlineKeyboardButton("➡️ Далее", callback_data="prologue_next")]
    ])

    full_text = ""

    for i, part in enumerate(PROLOGUE_PARTS):
        full_text += part + "\n\n"

        if i == len(PROLOGUE_PARTS) - 1:
            await context.bot.send_message(
                chat_id=chat_id,
                text=full_text,
                parse_mode='Markdown'
            )
        else:
            await context.bot.send_message(
                chat_id=chat_id,
                text=full_text,
                reply_markup=next_keyboard,
                parse_mode='Markdown'
            )
            # Ждём нажатия "Далее" через callback

    # Выбор пути
    choice_keyboard = InlineKeyboardMarkup([
        [InlineKeyboardButton("🌿 К болоту", callback_data="go_left")],
        [InlineKeyboardButton("⛰️ К скалам", callback_data="go_right")]
    ])

    await context.bot.send_message(
        chat_id=chat_id,
        text="Куда ты направишься?",
        reply_markup=choice_keyboard
    )


async def prologue_next(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()
    await query.edit_message_reply_markup(reply_markup=None)