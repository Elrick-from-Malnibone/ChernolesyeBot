async def send_prologue(update: Update, context: ContextTypes.DEFAULT_TYPE):
    chat_id = update.effective_chat.id
    message_id = update.message.message_id  # ID сообщения, на которое отвечаем

    # Кнопка "Пропустить"
    skip_keyboard = InlineKeyboardMarkup([
        [InlineKeyboardButton("⏭ Пропустить", callback_data="skip_prologue")]
    ])

    # Отправляем первый черновик
    await context.bot._post(
        "sendMessageDraft",
        {
            "chat_id": chat_id,
            "message_id": message_id,
            "draft_id": message_id,
            "text": "⚔️ Пролог...",
            "reply_markup": skip_keyboard.to_json()
        }
    )

    full_text = ""

    for part in PROLOGUE_PARTS:
        full_text += part + "\n\n"
        
        await context.bot._post(
            "sendMessageDraft",
            {
                "chat_id": chat_id,
                "message_id": message_id,
                "draft_id": message_id,
                "text": full_text[:4096],
                "reply_markup": skip_keyboard.to_json()
            }
        )
        
        await asyncio.sleep(2)  # пауза, чтобы стриминг выглядел как живой

    # Убираем кнопку в конце
    await context.bot.edit_message_reply_markup(
        chat_id=chat_id,
        message_id=message_id,
        reply_markup=None
    )


async def skip_prologue(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    chat_id = query.message.chat.id
    message_id = query.message.message_id

    full_text = "\n\n".join(PROLOGUE_PARTS)

    # Отправляем весь текст сразу
    await context.bot.edit_message_text(
        chat_id=chat_id,
        message_id=message_id,
        text=full_text,
        reply_markup=None
    )