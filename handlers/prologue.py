async def send_prologue(update: Update, context: ContextTypes.DEFAULT_TYPE):
    chat_id = update.effective_chat.id

    # 1. Отправляем картинку
    try:
        with open("images/prologue.jpg", "rb") as f:
            await context.bot.send_photo(chat_id=chat_id, photo=InputFile(f))
    except:
        # Если картинки нет — просто идём дальше
        await context.bot.send_message(chat_id, "🖼 Картинка не найдена")

    # 2. Отправляем первую часть с кнопкой "Пропустить"
    skip_keyboard = InlineKeyboardMarkup([
        [InlineKeyboardButton("⏭ Пропустить", callback_data="skip_prologue")]
    ])

    first_msg = await context.bot.send_message(
        chat_id=chat_id,
        text=PROLOGUE_PARTS[0],
        reply_markup=skip_keyboard
    )

    full_text = PROLOGUE_PARTS[0]

    # 3. Постепенно отправляем остальные части НОВЫМИ сообщениями
    for part in PROLOGUE_PARTS[1:]:
        await asyncio.sleep(2)
        full_text += "\n\n" + part

        # Редактируем первое сообщение, заменяя текст
        await context.bot.edit_message_text(
            chat_id=chat_id,
            message_id=first_msg.message_id,
            text=full_text,
            reply_markup=skip_keyboard
        )

    # 4. Убираем кнопку "Пропустить" в конце
    await context.bot.edit_message_text(
        chat_id=chat_id,
        message_id=first_msg.message_id,
        text=full_text
    )


async def skip_prologue(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    chat_id = query.message.chat.id
    message_id = query.message.message_id

    full_text = "\n\n".join(PROLOGUE_PARTS)

    await context.bot.edit_message_text(
        chat_id=chat_id,
        message_id=message_id,
        text=full_text
    )